/**
 * sync-abi — copies contract ABIs from Foundry's `out/` and deployment files from `deployment/` into this package.
 *
 *   pnpm --filter @runwaymind/shared run sync-abi                  # all deployment/*.json
 *   pnpm --filter @runwaymind/shared run sync-abi -- --network fuji # only deployment/fuji*.json
 *
 * Writes src/abi/<Name>.ts (`export const <name>Abi = [...] as const`), src/abi/index.ts, and
 * src/deployments/<file>.json. Run `forge build` first.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REQUIRED_CONTRACTS = [
  'Treasury',
  'ObligationRegistry',
  'PolicyEngine',
  'VaultAdapter',
  'MockLendingPool',
  'MockUSDC',
] as const;
const OPTIONAL_CONTRACTS = ['AaveV3Adapter'] as const;

export function abiConstName(contract: string): string {
  return `${contract.charAt(0).toLowerCase()}${contract.slice(1)}Abi`;
}

export function renderAbiModule(contract: string, abi: unknown): string {
  return (
    `// Generated by scripts/sync-abi.ts from out/${contract}.sol/${contract}.json — do not edit.\n` +
    `export const ${abiConstName(contract)} = ${JSON.stringify(abi, null, 2)} as const;\n`
  );
}

/** src/deployments/index.ts: raw deployment JSON keyed by file name (validate with loadDeployment). */
export function renderDeploymentsIndex(files: string[]): string {
  const json = files.filter((f) => f.endsWith('.json')).sort();
  const ident = (f: string) => f.replace(/\.json$/, '').replace(/[^a-zA-Z0-9]/g, '_');
  return (
    '// Generated by scripts/sync-abi.ts — do not edit.\n' +
    json.map((f) => `import ${ident(f)} from './${f}';`).join('\n') +
    (json.length ? '\n\n' : '') +
    `export const deploymentFiles: Record<string, unknown> = { ${json.map((f) => `'${f.replace(/\.json$/, '')}': ${ident(f)}`).join(', ')} };\n`
  );
}

interface Options {
  repoRoot: string;
  packageRoot: string;
  network: string | null;
}

function parseArgs(argv: string[]): { network: string | null } {
  const i = argv.indexOf('--network');
  return { network: i >= 0 ? (argv[i + 1] ?? null) : null };
}

export function syncAbi({ repoRoot, packageRoot, network }: Options): { abis: string[]; deployments: string[] } {
  const outDir = join(repoRoot, 'out');
  const abiDir = join(packageRoot, 'src', 'abi');
  const deploymentsSrc = join(repoRoot, 'deployment');
  const deploymentsDst = join(packageRoot, 'src', 'deployments');

  if (!existsSync(outDir)) throw new Error(`Foundry output not found at ${outDir}. Run \`forge build\` first.`);
  mkdirSync(abiDir, { recursive: true });

  const written: string[] = [];
  for (const contract of [...REQUIRED_CONTRACTS, ...OPTIONAL_CONTRACTS]) {
    const artifact = join(outDir, `${contract}.sol`, `${contract}.json`);
    if (!existsSync(artifact)) {
      if ((REQUIRED_CONTRACTS as readonly string[]).includes(contract)) {
        throw new Error(`Missing artifact ${artifact}. Did \`forge build\` compile ${contract}?`);
      }
      continue; // optional (AaveV3Adapter)
    }
    const { abi } = JSON.parse(readFileSync(artifact, 'utf8')) as { abi: unknown };
    writeFileSync(join(abiDir, `${contract}.ts`), renderAbiModule(contract, abi));
    written.push(contract);
  }

  const index =
    '// Generated by scripts/sync-abi.ts — do not edit.\n' +
    written.map((c) => `export { ${abiConstName(c)} } from './${c}';`).join('\n') +
    '\n';
  writeFileSync(join(abiDir, 'index.ts'), index);

  const copied: string[] = [];
  if (existsSync(deploymentsSrc)) {
    mkdirSync(deploymentsDst, { recursive: true });
    for (const file of readdirSync(deploymentsSrc)) {
      if (!file.endsWith('.json')) continue;
      if (network && !file.startsWith(network)) continue;
      copyFileSync(join(deploymentsSrc, file), join(deploymentsDst, file));
      copied.push(file);
    }
  }
  mkdirSync(deploymentsDst, { recursive: true });
  writeFileSync(join(deploymentsDst, 'index.ts'), renderDeploymentsIndex(readdirSync(deploymentsDst)));
  return { abis: written, deployments: copied };
}

const isMain = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const repoRoot = resolve(packageRoot, '..', '..');
  const { network } = parseArgs(process.argv.slice(2));
  const result = syncAbi({ repoRoot, packageRoot, network });
  console.log(`ABIs: ${result.abis.join(', ')}`);
  console.log(`Deployments: ${result.deployments.length ? result.deployments.join(', ') : '(none)'}`);
}
